async function renderIcon(iconData, color) {
	const renderData = iconToSVG(iconData, { height: ICON_SIZE })
	const svg = iconToHTML(renderData.body, {
		...renderData.attributes,
		color,
	})
	const resvg = new Resvg(svg, {
		font: { loadSystemFonts: false },
		fitTo: { mode: 'width', value: ICON_SIZE },
	})
	const rendered = resvg.render()
	const png64 = Buffer.from(rendered.asPng()).toString('base64')
	rendered.free()
	resvg.free()
	return png64
}

async function main() {
	const wasmPath = require.resolve('@resvg/resvg-wasm/index_bg.wasm')
	await initWasm(await readFile(wasmPath))

	const entries = []
	for (const name of MDI_ICONS) {
		const iconData = getIconData(mdiIcons, name)
		if (!iconData) {
			throw new Error(`Unknown MDI icon: ${name}`)
		}
		const light = await renderIcon(iconData, ICON_COLORS.light)
		const dark = await renderIcon(iconData, ICON_COLORS.dark)
		entries.push(`\t'${name}': {\n\t\tlight: '${light}',\n\t\tdark: '${dark}',\n\t},`)
	}

	const content = [
		'// Auto-generated by scripts/generate-icons.mjs. Do not edit manually.',
		"export type IconVariant = 'light' | 'dark'",
		'',
		'export const GENERATED_ICONS: Record<string, Record<IconVariant, string>> = {',
		...entries,
		'}',
		'',
	].join('\n')

	await mkdir(dirname(OUT_FILE), { recursive: true })
	await writeFile(OUT_FILE, content, 'utf8')
	console.log(`Generated ${entries.length} MDI icons (light & dark) -> src/generated/icons.ts`)
}

await main()
